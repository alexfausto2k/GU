async function guardar(c, u, v, antigos) {
  if (await c.match(u)) return;
  for (const k of antigos) { // mesmo arquivo numa versão anterior do app: reaproveita sem baixar
    const r = await (await caches.open(k)).match(u);
    if (r && r.headers.get("x-gu-v") === v) { await c.put(u, r); return; }
  }
  const r = await fetch(new Request(u, {cache: "reload"}));
  if (!r.ok) throw new Error(u + " " + r.status);
  const b = await r.blob();
  await c.put(u, new Response(b, {headers: {"content-type": r.headers.get("content-type") || b.type || "application/octet-stream", "x-gu-v": v}}));
}

